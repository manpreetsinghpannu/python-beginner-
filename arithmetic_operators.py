friends = 5

friends *= 2  # or friends = friends * 2
print(friends)  # Output: 10
# it is the function of multiplication

friends += 5  # or friends = friends + 5
print(friends)  # Output: 15
# it is the function of addition

friends -= 3  # or friends = friends - 3
print(friends)  # Output: 12
# it is the function of subtraction

friends /= 2  # or friends = friends / 2
print(friends)  # Output: 6.0
# it is the function of division and it returns a float value

friends **= 2  # or friends = friends ** 2
print(friends)  # Output: 36.0
# it is the function of exponentiation and it returns a float value

friends %= 5  # or friends = friends % 5
print(friends)  # Output: 1.0
# it is the function of the remainder after division

friends //= 2  # or friends = friends // 2
print(friends)  # Output: 0.0
# it is the function of floor division and it returns a float value

remainder = friends % 3
print(remainder)  # Output: 0.0
# it is the function of the remainder after division
